const app = document.getElementById("app");

function createSnowLayer() {
  const snowLayer = document.querySelector(".snow-layer");
  if (!snowLayer) return;

  snowLayer.innerHTML = "";

  const flakes = 90;
  for (let i = 0; i < flakes; i++) {
    const flake = document.createElement("span");
    flake.className = "snow";
    flake.style.left = `${Math.random() * 100}%`;
    flake.style.animationDuration = `${5 + Math.random() * 7}s`;
    flake.style.animationDelay = `${Math.random() * -10}s`;

    const size = 3 + Math.random() * 8;
    const opacity = 0.35 + Math.random() * 0.65;
    flake.style.setProperty("--flake-size", `${size.toFixed(1)}px`);
    flake.style.setProperty("--flake-opacity", opacity.toFixed(2));
    flake.style.setProperty("--drift", `${(-45 + Math.random() * 90).toFixed(2)}px`);
    snowLayer.appendChild(flake);
  }
}

function parseLocalDate(dateString) {
  const [year, month, day] = dateString.split("-").map(Number);
  return new Date(year, month - 1, day);
}

function normalizeToday() {
  const now = new Date();
  return new Date(now.getFullYear(), now.getMonth(), now.getDate());
}

function formatDate(dateString) {
  const date = parseLocalDate(dateString);
  return new Intl.DateTimeFormat("es-ES", {
    day: "2-digit",
    month: "long",
    year: "numeric"
  }).format(date);
}

